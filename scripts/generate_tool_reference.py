"""Regenerate docs/TOOLS.md from the server's own tool definitions.

    .venv/bin/python scripts/generate_tool_reference.py          # write docs/TOOLS.md
    .venv/bin/python scripts/generate_tool_reference.py --check  # exit 1 if it is out of date

It builds the server against a throwaway data directory and never contacts YouTube or reads credentials.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import anyio

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from mcp import Client  # noqa: E402

from youtube_mcp.config import Settings  # noqa: E402
from youtube_mcp.server import build_server, create_service  # noqa: E402

OUT = ROOT / "docs" / "TOOLS.md"

SECTIONS = [
    ("Uploading and managing videos", ["upload_video", "get_upload_progress", "update_metadata", "set_thumbnail",
                                       "set_visibility", "get_video_status", "get_share_link", "list_uploads",
                                       "get_channel_info"]),
    ("Captions", ["upload_captions", "list_captions", "download_captions", "update_captions"]),
    ("Playlists", ["list_playlists", "create_playlist", "update_playlist", "list_playlist_items", "add_to_playlist",
                   "remove_from_playlist"]),
    ("Categories", ["list_categories"]),
    ("Scheduled publishing", ["schedule_publish", "get_publish_schedule", "cancel_publish_schedule"]),
    ("Analytics (optional)", ["get_channel_analytics", "get_video_analytics", "get_top_videos"]),
]


def _type(schema: dict) -> str:
    if "anyOf" in schema:
        parts = [_type(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " or ".join(parts) + (" (nullable)" if any(s.get("type") == "null" for s in schema["anyOf"]) else "")
    if "enum" in schema:
        return " | ".join(f"`{v}`" for v in schema["enum"])
    if schema.get("type") == "array":
        return f"list of {_type(schema.get('items', {}))}"
    return schema.get("type", "any")


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render(tools: dict) -> str:
    out = ["# Tool reference", "",
           "<!-- Generated by scripts/generate_tool_reference.py from the server's tool definitions. "
           "Do not edit by hand. -->", "",
           f"The server exposes {len(tools)} tools. **Approval** says how a tool changes YouTube:", "",
           "- *read-only*: never changes anything.",
           "- *two-step*: the first call returns a preview and a `confirmation_token`; only a second call with the same "
           "arguments plus that token performs the change. See [Security model](SECURITY.md).",
           "- *two-step + public*: making something public also needs `confirm_public=true` and the native macOS "
           "dialog.", "",
           "Two-step tools without `confirm_public` can still show the native dialog when the change would expose "
           "content publicly: publishing a non-draft caption track on a public video, or adding an unlisted video to "
           "a public playlist.", "",
           "Every write result reports `write_accepted`, `verified`, `verification` and `requires_manual_attention`; "
           "see [Verification after writes](BEHAVIOUR.md#verification-after-writes).", ""]
    listed = [n for _, names in SECTIONS for n in names]
    missing = sorted(set(tools) - set(listed))
    sections = SECTIONS + ([("Other", missing)] if missing else [])
    for title, names in sections:
        out += [f"## {title}", ""]
        for name in names:
            t = tools[name]
            ann = t.annotations
            approval = "read-only" if ann and ann.read_only_hint else (
                "two-step" if "confirmation_token" in t.input_schema.get("properties", {})
                else "read-only on YouTube; may copy to the local clipboard")
            if "confirm_public" in t.input_schema.get("properties", {}):
                approval += " + public"
            out += [f"### `{name}`", "", f"*{t.title or name}* · **{approval}**", "", _cell(t.description or ""), ""]
            props = t.input_schema.get("properties", {})
            required = set(t.input_schema.get("required", []))
            if props:
                out += ["| Parameter | Type | Required | Default | Description |", "|---|---|---|---|---|"]
                for pname, p in props.items():
                    default = "" if pname in required or "default" not in p else f"`{p['default']!r}`"
                    out.append(f"| `{pname}` | {_cell(_type(p))} | {'yes' if pname in required else 'no'} | "
                               f"{_cell(default)} | {_cell(p.get('description', ''))} |")
                out.append("")
            else:
                out += ["No parameters.", ""]
    return "\n".join(out).rstrip() + "\n"


async def collect() -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        settings = Settings(client_secret_file=t / "none.json", token_file=t / "none-token.json", data_dir=t / "data")
        server = build_server(create_service(settings))
        async with Client(server) as client:
            return {tool.name: tool for tool in (await client.list_tools()).tools}


def main() -> int:
    text = render(anyio.run(collect))
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("docs/TOOLS.md is out of date; run scripts/generate_tool_reference.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
